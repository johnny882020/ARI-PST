#!/usr/bin/env python3
"""Generate infra/render.staging.yaml from render.yaml. Use --check in CI to detect drift.
Staging: branch staging, names prefixed ari-stg-, auto-deploy after CI (checksPass), 1 API instance,
SEED_SYNTHETIC=true, smaller database. Synthetic data only."""
import copy, sys, pathlib, yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "render.yaml"
OUT = ROOT / "infra" / "render.staging.yaml"
HEADER = ("# GENERATED by scripts/gen-staging.py from render.yaml. Do not edit by hand.\n"
          "# Staging Blueprint. Tracks branch: staging. Synthetic data only.\n")


def rename(name):
    return name.replace("ari-", "ari-stg-", 1) if name.startswith("ari-") else name


def build():
    d = yaml.safe_load(SRC.read_text())
    s = copy.deepcopy(d)
    s["previews"] = {"generation": "off"}  # previews come from the production Blueprint only
    for g in s["envVarGroups"]:
        g["name"] = rename(g["name"])
        if g["name"] == "ari-stg-common":
            g["envVars"] = [e for e in g["envVars"] if e["key"] != "DATA_CLASSIFICATION"] + [
                {"key": "DATA_CLASSIFICATION", "value": "synthetic"},
                {"key": "SEED_SYNTHETIC", "value": "true"},
                {"key": "APP_ENV", "value": "staging"},
            ]
    for db in s["databases"]:
        db["name"] = rename(db["name"])
        db["databaseName"] = "ari_portal_stg"
        db["plan"] = "basic-1gb"
        db["diskSizeGB"] = 5
        db.pop("previewPlan", None)
        db.pop("previewDiskSizeGB", None)
    for sv in s["services"]:
        sv["name"] = rename(sv["name"])
        sv["branch"] = "staging"
        sv.pop("previews", None)
        sv.pop("previewPlan", None)
        sv["autoDeployTrigger"] = "checksPass"
        if sv["name"] == "ari-stg-api":
            sv["numInstances"] = 1
        for e in sv.get("envVars", []):
            if "fromGroup" in e:
                e["fromGroup"] = rename(e["fromGroup"])
            if "fromDatabase" in e:
                e["fromDatabase"]["name"] = rename(e["fromDatabase"]["name"])
    for g in s["envVarGroups"]:
        pass
    return HEADER + yaml.safe_dump(s, sort_keys=False, width=200)


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("infra/render.staging.yaml is out of date. Run: python3 scripts/gen-staging.py")
            return 1
        print("staging blueprint is in sync")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
